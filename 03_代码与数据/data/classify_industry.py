def strip_company(name: str) -> str:
    """反复剥离尾部的基金公司后缀。"""
    changed = True
    n = name
    while changed:
        changed = False
        for c in COMPANIES:
            if n.endswith(c) and len(n) > len(c) + 2:
                n = n[: -len(c)]
                changed = True
                break
    return n


# 跨境 QDII 标的（非 A 股/港股行业，剔除）
QDII_PAT = re.compile(r"标普|纳斯达克|纳指|道琼斯|德国|法国|CAC|DAX|日本|日经|沙特|亚太|"
                      r"全球|海外|美国|英国|印度|东南亚|巴西|墨西哥|意大利|西班牙|中概")


def classify(name: str):
    n = strip_company(name)
    if QDII_PAT.search(n):
        return None  # QDII 不收
    market = "港股" if re.search(r"港股|恒生|香港|沪港深", n) else "A股"
    for industry, sector, kws in INDUSTRY_RULES:
        for kw in kws:
            if kw in n:
                return industry, sector, market
    return None  # 未命中行业即淘汰（只收行业 ETF）


def main():
    etfs = json.load(open(os.path.join(BASE, "etf_names.json"), encoding="utf-8"))
    out = {}
    for f in etfs:
        if re.search(r"货币|联接|FOF|联接基金", f["name"]):
            continue
        r = classify(f["name"])
        if not r:
            continue
        industry, sector, market = r
        # 不去重：不同公司的同名 ETF 是不同产品（如 证券ETF国泰/证券ETF华宝），
        # 仅剔除同一代码重复出现
        out[f["code"]] = {"code": f["code"], "name": f["name"],
                          "industry": industry, "sector": sector,
                          "market": market, "type": f["type"]}
    items = sorted(out.values(), key=lambda x: (x["sector"], x["industry"], x["code"]))
    json.dump(items, open(os.path.join(BASE, "etf_industry.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    from collections import Counter
    c = Counter((x["sector"], x["industry"]) for x in items)
    print("行业 ETF 命中:", len(items), "覆盖行业数:", len(c))
    for (sec, ind), v in sorted(c.items()):
        print("  %-8s %-12s %d" % (sec, ind, v))


if __name__ == "__main__":
    main()
